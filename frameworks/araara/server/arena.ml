(* HttpArena benchmark server for araara / hcs.
   https://github.com/MDA2AV/HttpArena

   One process, four listeners, every listener bound on each Eio domain with
   SO_REUSEPORT:

     8080  plaintext: HTTP/1.1, h2c (prior knowledge) and WebSocket /ws
     8081  TLS, ALPN http/1.1 only      — /json (json-tls), /echo (8gbit), /static
     8082  cleartext h2c                — /baseline2, /json
     8443  TLS, ALPN h2 + http/1.1      — /baseline2, /static, gRPC

   Everything goes through the framework: Hcs.Router for dispatch,
   Hcs.Request / Hcs.Response accessors and constructors, Hcs.Plug.Compress
   for negotiated JSON compression, Hcs.Plug.Static for files, Hcs.Grpc for
   the gRPC transport (codecs generated by ocaml-protoc), simdjsont for JSON
   and repodb for Postgres. See meta.json for the subscribed profiles. *)

(* ── Dataset and typed JSON codecs ─────────────────────────────────────── *)

type item = {
  id : int;
  name : string;
  category : string;
  price : int;
  quantity : int;
  active : bool;
  tags : string list;
  rating : int * int;
  total : int option;
}

(* Codecs describe shapes, not values: build them once. *)
let tags_codec = Simdjsont.Codec.(list string)

let rating_codec =
  let open Simdjsont.Codec in
  Obj.field (fun score count -> (score, count))
  |> Obj.mem "score" int ~enc:fst
  |> Obj.mem "count" int ~enc:snd
  |> Obj.finish

let item_codec =
  let open Simdjsont.Codec in
  Obj.field (fun id name category price quantity active tags rating total ->
      { id; name; category; price; quantity; active; tags; rating; total })
  |> Obj.mem "id" int ~enc:(fun i -> i.id)
  |> Obj.mem "name" string ~enc:(fun i -> i.name)
  |> Obj.mem "category" string ~enc:(fun i -> i.category)
  |> Obj.mem "price" int ~enc:(fun i -> i.price)
  |> Obj.mem "quantity" int ~enc:(fun i -> i.quantity)
  |> Obj.mem "active" bool ~enc:(fun i -> i.active)
  |> Obj.mem "tags" tags_codec ~enc:(fun i -> i.tags)
  |> Obj.mem "rating" rating_codec ~enc:(fun i -> i.rating)
  |> Obj.opt_mem "total" int ~enc:(fun i -> i.total)
  |> Obj.finish

let items_codec =
  let open Simdjsont.Codec in
  Obj.field (fun items count -> (items, count))
  |> Obj.mem "items" (list item_codec) ~enc:fst
  |> Obj.mem "count" int ~enc:snd
  |> Obj.finish

let load_dataset path =
  let body = In_channel.with_open_bin path In_channel.input_all in
  match
    Simdjsont.Codec.decode_string (Simdjsont.Codec.array item_codec) body
  with
  | Ok items -> items
  | Error message -> failwith ("Invalid HttpArena dataset: " ^ message)

(* Serialized on every request; the body is never cached. *)
let respond_items items =
  Hcs.Response.json
    (Simdjsont.Codec.encode_string items_codec (items, List.length items))

(* ── HTTP handlers ─────────────────────────────────────────────────────── *)

let handle_baseline _params req =
  let sum =
    Hcs.Request.query_int_or ~default:0 req "a"
    + Hcs.Request.query_int_or ~default:0 req "b"
  in
  let body_sum =
    if Hcs.Request.is_post req then
      Option.value ~default:0
        (int_of_string_opt (String.trim (Hcs.Request.body req)))
    else 0
  in
  Hcs.Response.text (string_of_int (sum + body_sum))

let handle_pipeline _params _req = Hcs.Response.text "ok"

let handle_json dataset params req =
  let count =
    Hcs.Router.param_int_or "count" ~default:0 params
    |> max 0
    |> min (Array.length dataset)
  in
  let m = Hcs.Request.query_int_or ~default:1 req "m" in
  let items =
    List.init count (fun n ->
        let item = dataset.(n) in
        { item with total = Some (item.price * item.quantity * m) })
  in
  respond_items items

(* The delay is read from the path on every request and waited with the
   framework's own mechanism: the handler's fiber sleeps on the Eio clock while
   the domain keeps serving its other connections. *)
let handle_delay clock params _req =
  match Hcs.Router.param_int "ms" params with
  | Some ms when ms >= 0 ->
      if ms > 0 then Eio.Time.sleep clock (float_of_int ms /. 1000.);
      Hcs.Response.text (string_of_int ms)
  | _ -> Hcs.Response.bad_request ()

(* The body is read through the framework (Content-Length or chunked) and
   written back as the response body. *)
let handle_echo _params req =
  Hcs.Response.make
    ~headers:[ ("Content-Type", "application/octet-stream") ]
    (Hcs.Request.body req)

(* ── Static files ──────────────────────────────────────────────────────── *)

(* Hcs.Plug.Static.server is hcs's static file handler: it stats the file on
   every request and serves it from its own cache while the size, modification
   time and inode are unchanged, so a replaced file is served from the next
   response on. With [precompressed] it serves the on-disk .br / .gz twin the
   client accepts, with the original Content-Type and the matching
   Content-Encoding. The root is the harness's /data directory, so the request
   path /static/<file> maps onto /data/static/<file>. *)
let static_config = { Hcs.Plug.Static.default_config with precompressed = true }

(* ── Postgres (async-db) ───────────────────────────────────────────────── *)

module Db = Repodb_postgresql
module Db_pool = Repodb.Pool.Make (Db)
module Repo = Repodb.Repo.Make (Db.Driver)

let item_column name ty = Repodb.Expr.qualified ~source:"items" ~column:name ty
let price_column = item_column "price" Repodb.Types.int

let items_query =
  let open Repodb in
  Query.from (Schema.table "items")
  |> Query.select
       Expr.
         [
           item_column "id" Types.int;
           item_column "name" Types.string;
           item_column "category" Types.string;
           price_column;
           item_column "quantity" Types.int;
           item_column "active" Types.bool;
           item_column "tags" Types.json;
           item_column "rating_score" Types.int;
           item_column "rating_count" Types.int;
         ]

let select_items mn mx lim =
  let open Repodb in
  items_query
  |> Query.where Expr.(between price_column (int mn) (int mx))
  |> Query.limit_expr (Expr.int lim)

let db_item row =
  let open Repodb.Driver in
  {
    id = row_int row 0;
    name = row_text row 1;
    category = row_text row 2;
    price = row_int row 3;
    quantity = row_int row 4;
    active = row_bool row 5;
    tags = Simdjsont.Codec.decode_string_exn tags_codec (row_text row 6);
    rating = (row_int row 7, row_int row 8);
    total = None;
  }

type database = { pool : Db_pool.t; slots : Eio.Semaphore.t }

let open_database ~share () =
  match Sys.getenv_opt "DATABASE_URL" with
  | Some url when url <> "" ->
      let allowance =
        match Sys.getenv_opt "DATABASE_MAX_CONN" with
        | Some s -> max 1 (Option.value ~default:256 (int_of_string_opt s))
        | None -> 256
      in
      let size = max 1 (allowance / max 1 share) in
      Some
        {
          pool = Db_pool.create ~max_size:size ~conninfo:url ();
          slots = Eio.Semaphore.make size;
        }
  | _ -> None

let handle_async_db database _params req =
  let mn = Hcs.Request.query_int_or ~default:10 req "min" in
  let mx = Hcs.Request.query_int_or ~default:50 req "max" in
  let lim = max 1 (min 50 (Hcs.Request.query_int_or ~default:50 req "limit")) in
  let items =
    match database with
    | None -> []
    | Some { pool; slots } -> (
        (* repodb's Postgres driver is synchronous libpq; the query runs on a
           system thread while this fiber waits. The semaphore keeps the number
           of threads within the connection budget. *)
        Eio.Semaphore.acquire slots;
        let result =
          Fun.protect
            ~finally:(fun () -> Eio.Semaphore.release slots)
            (fun () ->
              Eio_unix.run_in_systhread (fun () ->
                  Db_pool.with_connection pool (fun conn ->
                      Repo.all_query conn (select_items mn mx lim)
                        ~decode:db_item)))
        in
        match result with
        | Ok (Ok items) -> items
        | Ok (Error _) | Error _ -> [])
  in
  respond_items items

(* ── gRPC (unary-grpc, unary-grpc-tls) ─────────────────────────────────── *)

let grpc_service =
  let decode s = Benchmark.decode_pb_sum_request (Pbrt.Decoder.of_string s) in
  let encode reply =
    let enc = Pbrt.Encoder.create () in
    Benchmark.encode_pb_sum_reply reply enc;
    Pbrt.Encoder.to_string enc
  in
  let get_sum _ctx (request : Benchmark.sum_request) =
    Ok (Benchmark.make_sum_reply ~result:(request.a + request.b) ())
  in
  Hcs.Grpc.Server.(
    v ()
    |> add_service ~name:"benchmark.BenchmarkService"
         (Service.v ()
         |> Service.add_rpc ~name:"GetSum" ~rpc:(unary ~decode ~encode get_sum)
         ))

(* ── WebSocket echo ────────────────────────────────────────────────────── *)

let ws_handler (ws : Hcs.Websocket.t) =
  let rec loop () =
    match Hcs.Websocket.recv_message ws with
    | Ok (Hcs.Websocket.Opcode.Text, msg) -> (
        match Hcs.Websocket.send_text ws msg with
        | Ok () -> loop ()
        | Error _ -> ())
    | Ok (Hcs.Websocket.Opcode.Binary, msg) -> (
        match Hcs.Websocket.send_binary ws msg with
        | Ok () -> loop ()
        | Error _ -> ())
    | Ok _ -> loop ()
    | Error _ -> ()
  in
  loop ()

(* ── Routing ───────────────────────────────────────────────────────────── *)

let make_handler ~sw ~clock ~static_root ~dataset ~database =
  let grpc = Hcs.Grpc.Server.handler ~sw grpc_service in
  let static = Hcs.Plug.Static.server ~config:static_config static_root in
  let compress = Hcs.Plug.Compress.create () in
  let router =
    Hcs.Router.compile
      Hcs.Router.Route.
        [
          get "/baseline11" handle_baseline;
          post "/baseline11" handle_baseline;
          get "/baseline2" handle_baseline;
          get "/pipeline" handle_pipeline;
          get "/json/:count" (handle_json dataset) |> plug compress;
          get "/delay/:ms" (handle_delay clock);
          post "/echo" handle_echo;
          get "/static/*" (fun _ req -> static req);
          get "/async-db" (handle_async_db database);
          post "/benchmark.BenchmarkService/GetSum" (fun _ req -> grpc req);
        ]
  in
  Hcs.Endpoint.to_handler
    (Hcs.Endpoint.router
       (Hcs.Endpoint.create Hcs.Endpoint.default_config)
       router)

(* ── Listeners ─────────────────────────────────────────────────────────── *)

(* The harness mounts the dataset, static files and certificates at fixed
   paths; the overrides exist for running the binary outside a container. *)
let env_path name default = Option.value ~default (Sys.getenv_opt name)
let data_dir = env_path "ARENA_DATA_DIR" "/data"
let certs_dir = env_path "ARENA_CERTS_DIR" "/certs"

let load_tls () =
  let cert_file = Filename.concat certs_dir "server.crt" in
  let key_file = Filename.concat certs_dir "server.key" in
  if Sys.file_exists cert_file && Sys.file_exists key_file then
    match Hcs.Tls_config.Server.of_pem ~cert_file ~key_file with
    | Ok tls -> Some tls
    | Error message -> failwith ("HttpArena TLS certificates: " ^ message)
  else None

(* hcs's documented server configuration with one change: SO_REUSEPORT, so
   every worker binds the same ports. The collector runs with the runtime's
   defaults, as the hcs deployment guide recommends. *)
let listener ?tls ~port protocol =
  { Hcs.Server.default_config with port; protocol; reuse_port = true; tls }

let listeners tls =
  let open Hcs.Server in
  let plain =
    [
      (listener ~port:8080 Auto_websocket, true);
      (listener ~port:8082 Http2_only, false);
    ]
  in
  match tls with
  | None -> plain
  | Some tls ->
      plain
      @ [
          ( listener ~port:8443 Auto
              ~tls:(Hcs.Tls_config.Server.h2_or_http11 tls),
            false );
          ( listener ~port:8081 Http1_only
              ~tls:(Hcs.Tls_config.Server.h1_only tls),
            false );
        ]

(* Each domain runs every listener; the kernel spreads connections across the
   domains' SO_REUSEPORT sockets. The domain count follows the CPUs the
   container may use. *)
let serve env ~domains ~dataset ~database =
  let net = Eio.Stdenv.net env in
  let clock = Eio.Stdenv.clock env in
  let fs = Eio.Stdenv.fs env in
  let domain_mgr = Eio.Stdenv.domain_mgr env in
  let tls = load_tls () in
  let serve_one () =
    Eio.Switch.run @@ fun sw ->
    let static_root = Eio.Path.open_dir ~sw Eio.Path.(fs / data_dir) in
    let handler = make_handler ~sw ~clock ~static_root ~dataset ~database in
    Eio.Fiber.all
      (List.map
         (fun (config, websocket) () ->
           if websocket then
             Hcs.Server.run ~sw ~net ~clock ~config ~ws_handler handler
           else Hcs.Server.run ~sw ~net ~clock ~config handler)
         (listeners tls))
  in
  Eio.Fiber.all
    (List.init domains (fun i () ->
         if i = 0 then serve_one ()
         else Eio.Domain_manager.run domain_mgr serve_one))

(* Eio picks io_uring on Linux and falls back to epoll where the kernel lacks
   it; a seccomp or SELinux policy that refuses io_uring shows up as EACCES
   from the ring setup instead, which Eio does not fall back from. *)
let run_eio fn =
  try Eio_main.run fn
  with Unix.Unix_error (Unix.EACCES, "io_uring_queue_init", _) ->
    prerr_endline "[arena] io_uring unavailable, using epoll";
    Eio_posix.run fn

(* Workers: one single-domain process per CPU the container may use, each
   binding every listener, as the hcs deployment guide recommends for a server
   whose workers share nothing. ARENA_PROCESSES and ARENA_DOMAINS override the
   layout for local experiments. *)
let env_int name default =
  match Sys.getenv_opt name with
  | Some s -> (
      match int_of_string_opt s with Some n when n > 0 -> n | _ -> default)
  | None -> default

let rec supervise children =
  if children <> [] then (
    let pid, status = Unix.wait () in
    (match status with
    | Unix.WEXITED 0 -> ()
    | _ ->
        List.iter (fun p -> try Unix.kill p Sys.sigterm with _ -> ()) children;
        exit 1);
    supervise (List.filter (( <> ) pid) children))

(* Stop promptly on SIGTERM / SIGINT (docker stop) instead of being killed
   after the grace period. *)
let () =
  List.iter
    (fun signal -> Sys.set_signal signal (Sys.Signal_handle (fun _ -> exit 0)))
    [ Sys.sigterm; Sys.sigint ]

let () =
  let dataset = load_dataset (Filename.concat data_dir "dataset.json") in
  let cpus = Domain.recommended_domain_count () in
  let processes = env_int "ARENA_PROCESSES" cpus in
  let domains = env_int "ARENA_DOMAINS" (max 1 (cpus / processes)) in
  let run () =
    (* The connection allowance is the container's; each process takes its
       share. *)
    let database = open_database ~share:processes () in
    run_eio @@ fun env -> serve env ~domains ~dataset ~database
  in
  if processes <= 1 then run ()
  else
    let children =
      List.init processes (fun _ ->
          match Unix.fork () with
          | 0 ->
              run ();
              exit 0
          | pid -> pid)
    in
    supervise children
